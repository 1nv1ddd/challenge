"""Промпт маршрутизируемого ответа: обычный текст плюс обязательная строка CONFIDENCE."""

from __future__ import annotations

from ..providers import Message

SYSTEM_ROUTED_ANSWER = (
    "Ты — ассистент, который отвечает на вопрос пользователя по существу, без воды и без "
    "приветствий. Если вопрос требует вычислений или рассуждения — считай аккуратно и приводи "
    "только итог с коротким обоснованием.\n\n"
    "ОБЯЗАТЕЛЬНО: последней строкой ответа выведи ровно `CONFIDENCE: 0.NN` — свою оценку того, "
    "что ответ верен. Ничего после этой строки не пиши.\n\n"
    "Калибровка оценки:\n"
    "- 0.90–1.00 — знаешь точно, проверять нечего;\n"
    "- 0.70–0.89 — уверен, но есть нюанс или ответ зависит от трактовки вопроса;\n"
    "- 0.40–0.69 — считал в уме сложное, легко ошибиться, либо знание неточное;\n"
    "- ниже 0.40 — не знаешь, догадываешься или данных не хватает.\n\n"
    "Занижать оценку на всякий случай — плохо, завышать — ещё хуже: по ней решают, "
    "нужна ли перепроверка более сильной моделью. Если не знаешь — так и скажи в ответе "
    "и поставь низкую оценку, не выдумывай.\n\n"
    "Строка CONFIDENCE обязательна ВСЕГДА, даже если ответ — одно слово или одно число:\n"
    "```\n"
    "Столица Франции — Париж.\n"
    "CONFIDENCE: 0.98\n"
    "```"
)


def answer_messages(question: str) -> list[Message]:
    """Запрос к любому тиру: промпт одинаковый, различается только модель."""
    return [
        Message(role="system", content=SYSTEM_ROUTED_ANSWER),
        Message(role="user", content=question),
    ]
